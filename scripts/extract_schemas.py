#!/usr/bin/env python3
"""Extract Hermes' tool JSON Schemas verbatim into JSON + a CJS module.

Two extraction paths, because the sources differ:

* ``MEMORY_SCHEMA``, ``SKILLS_LIST_SCHEMA``, ``SKILL_VIEW_SCHEMA`` are plain
  module-level literals -> ``ast.literal_eval`` of the exact source segment.
* ``SKILL_MANAGE_SCHEMA`` is built from helper functions at import time, so the
  literal evaluator cannot see it. We exec the source segments of the helpers it
  depends on (in file order) plus the final assignment, then read the resulting
  object. Nothing is re-typed by hand.

Usage:
    python3 scripts/extract_schemas.py [path/to/hermes-agent]

Without an argument the script reads ``$HERMES_SRC`` or ``../hermes-agent``.
"""
import ast
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
OUT_JSON = HERE / 'src' / 'schemas.hermes.json'
OUT_JS = HERE / 'src' / 'tool_schemas.js'
SOURCE = 'NousResearch/hermes-agent@d923a5eb48 (v0.22.2)'


def hermes_root() -> Path:
    if len(sys.argv) > 1:
        return Path(sys.argv[1]).resolve()
    env = os.environ.get('HERMES_SRC')
    if env:
        return Path(env).resolve()
    return (HERE.parent / 'hermes-agent').resolve()


def module_nodes(src: str) -> dict:
    """Map top-level assignment / function names to their AST nodes."""
    found = {}
    for node in ast.parse(src).body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    found[target.id] = node
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            found[node.target.id] = node
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            found[node.name] = node
    return found


def literal(src: str, nodes: dict, name: str):
    node = nodes.get(name)
    if node is None:
        raise SystemExit(f'missing assignment: {name}')
    value = node.value if isinstance(node, ast.Assign) else node.value
    return ast.literal_eval(value)


def execute_segments(src: str, names: list[str], wanted: str):
    """Exec the named top-level segments in file order, then return ``wanted``."""
    nodes = module_nodes(src)
    segments = []
    ordered = sorted(names, key=lambda name: nodes[name].lineno)
    for name in ordered:
        segment = ast.get_source_segment(src, nodes[name])
        if segment is None:
            raise SystemExit(f'cannot segment {name}')
        segments.append(segment)
    namespace = {}
    exec(compile('\n\n'.join(segments), '<hermes-extract>', 'exec'), namespace)  # noqa: S102 - source is pinned
    if wanted not in namespace:
        raise SystemExit(f'{wanted} was not produced by the exec segment')
    return namespace[wanted]


def main() -> None:
    root = hermes_root()
    if not (root / 'tools').is_dir():
        raise SystemExit(f'not a hermes checkout: {root} (pass the path as argv[1] or $HERMES_SRC)')

    memory_src = (root / 'tools' / 'memory_tool.py').read_text(encoding='utf-8')
    skills_src = (root / 'tools' / 'skills_tool.py').read_text(encoding='utf-8')
    manager_src = (root / 'tools' / 'skill_manager_tool.py').read_text(encoding='utf-8')

    memory = literal(memory_src, module_nodes(memory_src), 'MEMORY_SCHEMA')
    skills_list = literal(skills_src, module_nodes(skills_src), 'SKILLS_LIST_SCHEMA')
    skill_view = literal(skills_src, module_nodes(skills_src), 'SKILL_VIEW_SCHEMA')
    skill_manage = execute_segments(
        manager_src,
        ['_skill_manage_description', '_NAME', '_OLD_STRING', '_NEW_STRING',
         '_FILE_PATH', '_op_schema', 'SKILL_MANAGE_SCHEMA'],
        'SKILL_MANAGE_SCHEMA',
    )

    schemas = [memory, skills_list, skill_view, skill_manage]
    for schema in schemas:
        if not isinstance(schema, dict) or 'name' not in schema or 'parameters' not in schema:
            raise SystemExit(f'extracted schema looks wrong: {schema!r:.120}')

    OUT_JSON.write_text(json.dumps(schemas, ensure_ascii=False, indent=1), encoding='utf-8')

    body = json.dumps({schema['name']: schema for schema in schemas}, ensure_ascii=False, indent=1)
    OUT_JS.write_text(
        "'use strict';\n"
        "/**\n"
        f" * Tool JSON Schemas copied VERBATIM from {SOURCE}.\n"
        " * Generated by scripts/extract_schemas.py — do not hand-edit.\n"
        " */\n"
        f'module.exports = {body};\n',
        encoding='utf-8',
    )

    print(f'wrote {OUT_JSON.relative_to(HERE)} and {OUT_JS.relative_to(HERE)}')
    for schema in schemas:
        params = schema.get('parameters') or {}
        print(f"  {schema['name']:14s} {len(json.dumps(schema)):6d} bytes, {len(params.get('properties') or {})} top-level props")


if __name__ == '__main__':
    main()